def sw_type(ir, t, optional=False):
    t = resolve(ir, t)
    k = t[0]
    base = {"str": "String", "int": "Int64", "num": "Double", "bool": "Bool", "json": "[String: JSONValue]"}.get(k) or (
        "[%s]" % sw_type(ir, t[1]) if k == "list" else "[String: %s]" % sw_type(ir, t[1]) if k == "map" else t[1])
    return base + ("?" if optional or k == "json" else "")


SWIFT_KEYWORDS = {"class", "default", "extension", "operator", "protocol", "self", "struct", "subscript", "type", "in", "is", "as", "init", "let", "var", "func"}


def sw_name(s):
    n = lcamel(s)
    return "`%s`" % n if n in SWIFT_KEYWORDS else n


