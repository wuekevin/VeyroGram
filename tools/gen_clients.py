def go_type(ir, t, ptr=False):
    t = resolve(ir, t)
    k = t[0]
    base = {"str": "string", "int": "int64", "num": "float64", "bool": "bool", "json": "map[string]any"}.get(k) or (
        "[]%s" % go_type(ir, t[1]) if k == "list" else "map[string]%s" % go_type(ir, t[1]) if k == "map" else t[1])
    return "*" + base if ptr and k in ("str", "int", "num", "bool", "ref") else base


GO_OPEN = '''func (v @N@) MarshalJSON() ([]byte, error) {
	type plain @N@
	b, err := json.Marshal(plain(v))
	if err != nil || len(v.Extra) == 0 {
		return b, err
	}
	var m map[string]json.RawMessage
	if err := json.Unmarshal(b, &m); err != nil {
		return nil, err
	}
	for k, x := range v.Extra {
		if _, known := m[k]; known {
			continue
		}
		raw, err := json.Marshal(x)
		if err != nil {
			return nil, err
		}
		m[k] = raw
	}
	return json.Marshal(m)
}

func (v *@N@) UnmarshalJSON(b []byte) error {
	type plain @N@
	if err := json.Unmarshal(b, (*plain)(v)); err != nil {
		return err
	}
	var m map[string]any
	if err := json.Unmarshal(b, &m); err != nil {
		return err
	}
	for _, k := range []string{@KNOWN@} {
		delete(m, k)
	}
	if len(m) > 0 {
		v.Extra = m
	}
	return nil
}
'''


