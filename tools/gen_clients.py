# -*- coding: utf-8 -*-
"""Generate the TypeScript, Go, Kotlin and Swift API clients from packages/contracts/openapi/*.yaml (Story 1.11, AD-8).

  gen_clients.py            write packages/clients/{typescript,go,kotlin,swift}
  gen_clients.py --check    regenerate in memory and fail if the files on disk differ (CI: a changed contract needs regenerated clients)

Why a small in-repo generator instead of openapi-generator: the contract uses a deliberately small subset of OpenAPI 3.1 (objects, arrays, maps,
strings with enums/patterns, integers, booleans, $ref, one nullable object), the generator fails loudly on anything outside it instead of guessing, and
nothing is downloaded or executed from a third party (AD-18). The generated clients have no third-party runtime dependencies except Kotlin's
kotlinx.serialization (the standard JSON library for Kotlin).

Every client: sends Authorization: Bearer from a caller-supplied token provider (token storage is the app's job, in the platform secure store),
parses the standard error envelope {code, message, trace_id, details} into one typed error, and treats unknown response fields as harmless.
"""
import glob, os, re, subprocess, sys
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPECS = os.path.join(ROOT, "packages/contracts/openapi")
OUT = os.path.join(ROOT, "packages/clients")
HEADER = "Generated by tools/gen_clients.py from packages/contracts/openapi. DO NOT EDIT: change the contract and regenerate."
# Schema names that would shadow a language built-in or a hand-written runtime type in the generated code.
RENAME = {"Error": "ErrorBody"}
METHODS = ("get", "post", "put", "patch", "delete")


class Unsupported(Exception):
    pass


# ---- contract -> IR --------------------------------------------------------------------------------------------------------------------------

class IR:
    def __init__(self):
        self.objects = {}   # name -> {"doc": str, "props": [(name, type, required, doc)]}
        self.aliases = {}   # name -> type
        self.ops = []
        self.version = None
        self.specs = {}

    # A type is a tuple: ("str",) ("int",) ("num",) ("bool",) ("json",) ("list", T) ("map", T) ("ref", Name)
    def conv(self, s, hint=None, spec=None):
        if "$ref" in s:
            name = RENAME.get(s["$ref"].split("/")[-1], s["$ref"].split("/")[-1])
            if "/schemas/" not in s["$ref"]:
                raise Unsupported("only #/components/schemas refs are supported: " + s["$ref"])
            return ("ref", name)
        t = s.get("type")
        if isinstance(t, list):
            non_null = [x for x in t if x != "null"]
            if non_null == ["object"]:
                return ("json",)  # object-or-null of unspecified shape
            raise Unsupported("type list %r" % (t,))
        for k in ("oneOf", "anyOf", "allOf", "not", "discriminator"):
            if k in s:
                raise Unsupported(k + " is not supported by the client generator")
        if t == "string":
            return ("str",)
        if t == "integer":
            return ("int",)
        if t == "number":
            return ("num",)
        if t == "boolean":
            return ("bool",)
        if t == "array":
            return ("list", self.conv(s["items"], hint and hint + "Item", spec))
        if t == "object" or "properties" in s:
            props = s.get("properties")
            ap = s.get("additionalProperties")
            if not props:
                if isinstance(ap, dict):
                    return ("map", self.conv(ap, hint and hint + "Value", spec))
                return ("json",)
            if not hint:
                raise Unsupported("anonymous object with properties needs a name")
            self.add_object(hint, s)
            return ("ref", hint)
        raise Unsupported("schema %r" % (s,))

    def add_object(self, name, s):
        req = set(s.get("required", []))
        props = []
        for pn, ps in s.get("properties", {}).items():
            props.append((pn, self.conv(ps, name + camel(pn)), pn in req, ps.get("description", "") if "$ref" not in ps else ""))
        ap = s.get("additionalProperties")
        obj = {"doc": s.get("description", ""), "props": props, "open": ap is True or isinstance(ap, dict)}
        shape = lambda o: [(n, t, r) for n, t, r, _ in o["props"]]
        if name in self.objects:
            # The same schema declared in several specs (the shared error envelope) merges; only the descriptions may differ.
            if shape(self.objects[name]) != shape(obj):
                raise Unsupported("two different schemas are both named " + name)
            return
        self.objects[name] = obj


def camel(s):
    return "".join(p[:1].upper() + p[1:] for p in re.split(r"[^A-Za-z0-9]+", s) if p)


def lcamel(s):
    c = camel(s)
    return c[:1].lower() + c[1:]


def load():
    ir = IR()
    for f in sorted(glob.glob(os.path.join(SPECS, "*.yaml"))):
        d = yaml.safe_load(open(f, encoding="utf-8"))
        ir.specs[os.path.basename(f)] = d
        ir.version = ir.version or d["info"]["version"]
        schemas = d.get("components", {}).get("schemas", {})
        for name, s in schemas.items():
            name = RENAME.get(name, name)
            if s.get("type") == "object" and s.get("properties"):
                ir.add_object(name, s)
            else:
                ir.aliases[name] = ir.conv(s, None, d)
    for fname, d in ir.specs.items():
        for path, item in d["paths"].items():
            shared = item.get("parameters", [])
            for m in METHODS:
                if m not in item:
                    continue
                o = item[m]
                opid = o["operationId"]
                params = []
                for p in shared + o.get("parameters", []):
                    if "$ref" in p:
                        raise Unsupported("parameter $ref in " + opid)
                    params.append({"name": p["name"], "in": p["in"], "required": bool(p.get("required")) or p["in"] == "path", "type": ir.conv(p.get("schema", {"type": "string"}))})
                for tpl in re.findall(r"\{([^}]+)\}", path):
                    if not any(p["name"] == tpl and p["in"] == "path" for p in params):
                        raise Unsupported("%s: path variable {%s} is not declared as a parameter" % (opid, tpl))
                body = None
                rb = o.get("requestBody")
                if rb and "$ref" in rb:
                    rb = d["components"]["requestBodies"][rb["$ref"].split("/")[-1]]
                if rb:
                    js = rb["content"].get("application/json")
                    if not js:
                        raise Unsupported(opid + ": only application/json request bodies are supported")
                    body = ir.conv(js["schema"], camel(opid) + "Request", d)
                resp, status = None, None
                for code, r in o["responses"].items():
                    if not str(code).startswith("2"):
                        continue
                    status = int(code)
                    if "$ref" in r:
                        r = d["components"]["responses"][r["$ref"].split("/")[-1]]
                    js = r.get("content", {}).get("application/json")
                    if js:
                        resp = ir.conv(js["schema"], camel(opid) + "Response", d)
                    break
                if status is None:
                    raise Unsupported(opid + ": no 2xx response")
                secured = "security" in o and bool(o["security"])
                ir.ops.append({"id": opid, "method": m.upper(), "path": path, "params": params, "body": body, "resp": resp, "status": status, "auth": secured,
                               "doc": (o.get("summary") or "").strip(), "tag": fname[:-5]})
    ir.ops.sort(key=lambda o: o["id"])
    return ir


def resolve(ir, t):
    while t[0] == "ref" and t[1] in ir.aliases:
        t = ir.aliases[t[1]]
    return t


def is_unit_enum_doc(s):
    return s


def ordered_objects(ir):
    return sorted(ir.objects.items())


def pathfmt(path, fmt):
    return re.sub(r"\{([^}]+)\}", lambda m: fmt(m.group(1)), path)


def one_line(s):
    return re.sub(r"\s+", " ", s or "").strip()


