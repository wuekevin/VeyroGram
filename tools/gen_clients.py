def generate():
    ir = load()
    files = {}
    for g in (gen_ts, gen_go, gen_kotlin, gen_swift):
        files.update(g(ir))
    # Go output is gofmt-formatted so that it is stable and passes the repository's format gate.
    r = subprocess.run(["gofmt"], input=files["go/client.go"], capture_output=True, text=True)
    if r.returncode != 0:
        raise Unsupported("gofmt rejected the generated Go client: " + r.stderr[:300])
    files["go/client.go"] = r.stdout
    return ir, files


def main():
    try:
        ir, files = generate()
    except Unsupported as e:
        print("gen_clients: the contract uses something the generator does not support: %s" % e)
        return 2
    if "--check" in sys.argv:
        stale = [p for p, c in files.items() if not os.path.exists(os.path.join(OUT, p)) or open(os.path.join(OUT, p), encoding="utf-8").read() != c]
