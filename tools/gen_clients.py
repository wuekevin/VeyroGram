def ts_type(ir, t):
    t = resolve(ir, t)
    k = t[0]
    return {"str": "string", "int": "number", "num": "number", "bool": "boolean", "json": "Record<string, unknown> | null"}.get(k) or (
        "Array<%s>" % ts_type(ir, t[1]) if k == "list" else "Record<string, %s>" % ts_type(ir, t[1]) if k == "map" else t[1])


